import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(readFileSync(new URL("../src/evidenceNavigation.ts", import.meta.url), "utf8"), {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const { transcriptTurns, evidenceTarget } = await import("data:text/javascript;base64," + Buffer.from(code).toString("base64"));
const text = "Salesperson: Hi 😀\nCustomer: Need help.";
const chars = Array.from(text);
const customerStart = Array.from("Salesperson: Hi 😀\nCustomer: ").length;
const transcript = {original_text: text, turns: [{start: 13, end: 17, role: "salesperson"}, {start: customerStart, end: chars.length, role: "customer"}]};
const turns = transcriptTurns(transcript);
assert.equal(turns[0].text, "Hi 😀");
assert.equal(turns[1].text, "Need help.");
assert.equal(evidenceTarget({quote: "Hi 😀", role: "salesperson"}, turns)?.id, "t0001");
assert.equal(evidenceTarget({quote: "Hi 😀", role: "customer"}, turns), null);
assert.equal(evidenceTarget({quote: "invented", role: "salesperson"}, turns), null);
assert.equal(evidenceTarget({quote: "Hi 😀", role: "salesperson"}, [turns[0], {...turns[0], id: "t0003"}]), null);
const anonymous = transcriptTurns({original_text: "First\n\nLast\r\n", turns: []});
assert.deepEqual(anonymous.map(t => [t.id, t.role, t.text]), [["t0001", null, "First\n"], ["t0003", null, "Last\r\n"]]);
assert.equal(evidenceTarget({quote: "Last\r\n", role: null}, anonymous)?.id, "t0003");
console.log("PASS: exact turn IDs/text/roles, Unicode spans, anonymous lines, wrong-role/unmatched/ambiguous evidence.");
